function optionKey(value: string): string {
  return value
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[’'`]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

const OPTION_EN_BY_KEY = new Map(
  Object.entries(OPTION_EN).map(([fr, en]) => [optionKey(fr), en] as const),
);

/** Traduction anglaise d'un choix du configurateur, ou la valeur telle quelle. */
export function optionToEnglish(value: string): string {
  if (typeof value !== 'string' || !value.trim()) return value;
  return OPTION_EN_BY_KEY.get(optionKey(value)) ?? value;
}

/** Affichage d'un choix selon la langue du document. */
export function displayOptionFor(value: string, lang: 'fr' | 'en'): string {
  return lang === 'en' ? optionToEnglish(value) : displayOption(value);
}
