const publishedAt = new Date('2026-10-27T00:00:00.000Z');
const approvedAt = new Date('2026-10-27T00:00:00.000Z');

function page(
  sourceKey: string,
  path: string,
  titleFr: string,
  contentFr: string,
  titleEn: string,
  contentEn: string,
  sourceType: PublicKnowledgeSeed['sourceType'] = 'MODULE_PAGE',
  authorityRank = 30,
): PublicKnowledgeSeed[] {
  return [
    {
      sourceKey,
      sourceType,
      canonicalUrl: `https://getcoro.io${path}`,
      title: titleFr,
      language: 'fr-CA',
      content: contentFr,
      authorityRank,
      publishedAt,
      sourceUpdatedAt: publishedAt,
    },
    {
      sourceKey,
      sourceType,
      canonicalUrl: `https://getcoro.io${path}?lang=en`,
      title: titleEn,
      language: 'en-CA',
      content: contentEn,
      authorityRank,
      publishedAt,
      sourceUpdatedAt: publishedAt,
    },
  ];
}

function capability(
  capabilityKey: string,
  path: string,
  nameFr: string,
  descriptionFr: string,
  nameEn: string,
  descriptionEn: string,
  status: NonNullable<PublicKnowledgeSeed['capability']>['status'],
): PublicKnowledgeSeed[] {
  return [
    {
      ...page(
        `capability-${capabilityKey}`,
        path,
        nameFr,
        descriptionFr,
        nameEn,
        descriptionEn,
        'PRODUCT_CAPABILITY',
        10,
      )[0],
      capability: {
        capabilityKey,
        name: nameFr,
        description: descriptionFr,
        status,
        approvedBy: 'FOUNDER_PUBLIC_CATALOGUE',
        approvedAt,
      },
    },
    {
      ...page(
        `capability-${capabilityKey}`,
        path,
        nameFr,
        descriptionFr,
        nameEn,
        descriptionEn,
        'PRODUCT_CAPABILITY',
        10,
      )[1],
      capability: {
        capabilityKey,
        name: nameEn,
        description: descriptionEn,
        status,
        approvedBy: 'FOUNDER_PUBLIC_CATALOGUE',
        approvedAt,
      },
    },
  ];
}

